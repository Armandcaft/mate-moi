import Database from 'better-sqlite3';
import { drizzle } from 'drizzle-orm/better-sqlite3';
import { migrate } from 'drizzle-orm/better-sqlite3/migrator';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import * as schema from './schema';

/** `DATABASE_PATH` points at the volume in production (`/data/mate-moi.db` on Fly.io). */
const path = process.env.DATABASE_PATH ?? 'data/mate-moi.db';
mkdirSync(dirname(path), { recursive: true });

const sqlite = new Database(path);
sqlite.pragma('journal_mode = WAL'); // also what Litestream needs
sqlite.pragma('foreign_keys = ON');
sqlite.pragma('busy_timeout = 5000');

export const db = drizzle(sqlite, { schema });

// Migrations are generated by `npm run db:generate` into ./drizzle and applied at start-up.
migrate(db, { migrationsFolder: process.env.MIGRATIONS_PATH ?? 'drizzle' });

export * from './schema';
